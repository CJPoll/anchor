defmodule Anchor.Domain.Sabotage.Record do
  @moduledoc """
  The sabotage record a `mix anchor.sabotage run` writes (DND-5484): the
  audit trail anchor ADR 003, crew ADR 008 and gen_saas ADR 26 require, in
  the repo's own file naming (`Anchor.Domain.Sabotage.RecordNaming`). Pure
  **Domain**: `render/2` returns the files to write, `%{path, content, mode}`,
  `mode` `:create` (a new file) or `:append` (a second run the same day, in
  the same domain and slot, adds a section).

  One record per (app, domain) the run touched under `:domain_date_slot`; one
  per app under `:ticket_nn_what` (that file name holds no domain). Sections,
  in order (`test/fixtures/sabotage/record_golden.md` is the authority for
  exact spacing):

    1. the title and header: Domain, Branch, Date (UTC), Code under test (every
       mutated `M.f/a`), Suite run, Generated by (the command, the Anchor
       version, the base and head SHAs);
    2. `## Summary` (DND-5643): a table, one row per mutant run (id,
       function, mutation, status, killer count), in the order of the
       sections below;
    3. `## Mutants`: per mutant run, its id, `M.f/a`, operator and variant,
       status, the patch as a diff block, the test command with its counts
       and failed tests, and the first failure as ExUnit printed it;
    4. `## Survivors`: each survivor and why it counts as one;
    5. `## Kills by timeout` (DND-5653): each mutant killed by time alone
       (the run's bound, or only ExUnit per-test timeouts), with its killers:
       no assertion failed under it, so the test it names is still lacking
       a red;
    6. `## Skipped, invalid, not run`: each with its reason, and the changed
       functions no mutant could be made of;
    7. `## Tests still lacking a red`: each new or changed test (in this
       record's app) that no mutant's run failed: it still needs a hand
       sabotage under the repo's ADR;
    8. `## Kill map`: the `anchor-kills` block (`Anchor.Domain.Sabotage.KillMap`).

  An appended section starts `## Run HH:MM UTC` and repeats sections 2 to 8
  one heading level down.

  `ctx`: `records` (the naming config, with `adr`: the rule a hand sabotage
  follows), `date` (`Date`), `time`
  (`"HH:MM"`), `branch`, `slot` (`RecordNaming.slot/2`), `base_sha`,
  `head_sha`, `command`, `version`, `test_command` (argv), `domain` (overrides the derived one, or `nil`),
  `changed_tests` (`ChangedTests` results), and `existing` (`dir =>` the
  record file names already there).
  """

  alias Anchor.Domain.Sabotage.KillMap
  alias Anchor.Domain.Sabotage.RecordNaming
  alias Anchor.Domain.Sabotage.Run

  @fence "```"

  @type entry :: %{path: String.t(), content: String.t(), mode: :create | :append}

  @doc """
  The record files of `run`, or `{:error, {reason, file}}` when a file cannot
  be named (`:no_ticket`, `:no_app`).
  """
  @spec render(Run.t(), map()) :: {:ok, [entry()]} | {:error, {atom(), String.t()}}
  def render(%Run{} = run, ctx) do
    run
    |> items()
    |> Enum.group_by(&group_key(&1, ctx))
    |> Enum.sort_by(fn {key, _items} -> key end)
    |> Enum.reduce_while({:ok, [], ctx.existing, MapSet.new()}, fn {key, items}, acc ->
      entry(key, items, run, ctx, acc)
    end)
    |> case do
      {:ok, entries, _existing, _lacking_done} -> {:ok, Enum.reverse(entries)}
      {:error, _reason} = error -> error
    end
  end

  @doc "The directories the kill-map reader lists: `dir`, `{app}` as `*`."
  @spec dir_glob(RecordNaming.config()) :: String.t()
  def dir_glob(%{dir: dir}), do: String.replace(dir, "{app}", "*")

  # -- grouping ---------------------------------------------------------------

  defp items(run) do
    Enum.map(run.outcomes, &{:outcome, &1}) ++
      Enum.map(run.skipped, &{:skipped, &1}) ++
      Enum.map(run.not_run, &{:not_run, &1}) ++
      Enum.map(run.errors, &{:error, &1})
  end

  defp file_module({:outcome, %{mutant: m}}), do: {m.file, m.module}
  defp file_module({:skipped, s}), do: {s.file, s.module}
  defp file_module({:not_run, m}), do: {m.file, m.module}
  defp file_module({:error, {f, _reason}}), do: {f.file, f.module}

  defp group_key(item, ctx) do
    {file, module} = file_module(item)
    {RecordNaming.app_for(file), group_domain(file, module, ctx)}
  end

  # A ticket-named file holds no domain, so it groups by app only.
  defp group_domain(_file, _module, %{records: %{naming: :ticket_nn_what}}), do: nil
  defp group_domain(_file, _module, %{domain: domain}) when is_binary(domain), do: domain
  defp group_domain(file, module, ctx), do: RecordNaming.domain_for(file, module, ctx.records)

  defp entry({app, domain}, items, run, ctx, {:ok, entries, existing, done}) do
    {file, module} = file_module(hd(items))
    domain = domain || Map.get(ctx, :domain) || RecordNaming.domain_for(file, module, ctx.records)

    with {:ok, dir} <- RecordNaming.dir(ctx.records, app),
         names = Map.get(existing, dir, []),
         naming = %{
           domain: domain,
           app: app,
           date: ctx.date,
           slot: ctx.slot,
           existing_names: names
         },
         {:ok, path} <- RecordNaming.path(ctx.records, naming) do
      name = Path.basename(path)
      mode = if name in names, do: :append, else: :create
      {lacking, done} = lacking(app, run, ctx, done)
      content = content(mode, domain, items, lacking, ctx)
      existing = Map.update(existing, dir, [name], &[name | &1])
      {:cont, {:ok, [%{path: path, content: content, mode: mode} | entries], existing, done}}
    else
      {:error, reason} -> {:halt, {:error, {reason, file}}}
    end
  end

  # The changed tests of this record's app that no mutant's run failed, listed
  # once per app (in its first record).
  defp lacking(app, run, ctx, done) do
    if MapSet.member?(done, app) do
      {[], done}
    else
      killed =
        for %{killers: killers} <- run.outcomes,
            {file, line, _name} <- killers,
            into: MapSet.new(),
            do: {file, line}

      tests =
        Enum.filter(ctx.changed_tests, fn test ->
          RecordNaming.app_for(test.file) == app and
            not MapSet.member?(killed, {test.file, test.line})
        end)

      {tests, MapSet.put(done, app)}
    end
  end

  # -- text -------------------------------------------------------------------

  defp content(:create, domain, items, lacking, ctx) do
    [
      "# Sabotage record: generated causal sabotage",
      "",
      header(domain, items, ctx),
      "",
      sections("##", items, lacking, ctx)
    ]
    |> Enum.join("\n")
  end

  defp content(:append, _domain, items, lacking, ctx) do
    [
      "## Run #{ctx.time} UTC",
      "",
      header_append(items, ctx),
      "",
      sections("###", items, lacking, ctx)
    ]
    |> Enum.join("\n")
  end

  defp header(domain, items, ctx) do
    [
      "- **Domain:** #{domain}",
      "- **Branch:** #{ctx.branch || "(detached HEAD)"}",
      "- **Date:** #{Date.to_iso8601(ctx.date)}",
      "- **Code under test:** #{code_under_test(items)}",
      "- **Suite run:** per mutant below (`#{Enum.join(ctx.test_command, " ")}` and its tests)",
      "- **Generated by:** #{generated_by(ctx)}"
    ]
    |> Enum.join("\n")
  end

  defp header_append(items, ctx) do
    [
      "- **Code under test:** #{code_under_test(items)}",
      "- **Generated by:** #{generated_by(ctx)}"
    ]
    |> Enum.join("\n")
  end

  defp generated_by(ctx),
    do:
      "`#{ctx.command}` (Anchor #{ctx.version}), base #{ctx.base_sha || "(unknown)"}, " <>
        "head #{ctx.head_sha || "(unknown)"}"

  defp code_under_test(items) do
    items
    |> Enum.flat_map(fn
      {:outcome, %{mutant: m}} -> ["`#{mfa(m)}`"]
      {:not_run, m} -> ["`#{mfa(m)}`"]
      _other -> []
    end)
    |> Enum.uniq()
    |> case do
      [] -> "(no mutant was run)"
      mfas -> Enum.join(mfas, ", ")
    end
  end

  defp sections(h, items, lacking, ctx) do
    outcomes = for {:outcome, o} <- items, do: o

    [
      "#{h} Summary",
      "",
      summary_table(outcomes),
      "#{h} Mutants",
      "",
      mutants(h <> "#", outcomes, ctx),
      "#{h} Survivors",
      "",
      survivors(outcomes),
      "#{h} Kills by timeout",
      "",
      timeout_kills(outcomes),
      "#{h} Skipped, invalid, not run",
      "",
      not_measured(items, outcomes),
      "#{h} Tests still lacking a red",
      "",
      lacking_lines(lacking, ctx),
      "#{h} Kill map",
      "",
      KillMap.render_block(outcomes)
    ]
    |> Enum.join("\n")
  end

  # DND-5643: one row per mutant run, in the order of its section below, so
  # the run reads at a glance; the sections keep the verbatim strings.
  defp summary_table([]), do: "None.\n"

  defp summary_table(outcomes) do
    rows =
      Enum.map_join(outcomes, "", fn %{mutant: m} = o ->
        cells = [m.id, "`#{mfa(m)}`", operator(m), o.status, length(o.killers)]
        "| " <> Enum.map_join(cells, " | ", &cell/1) <> " |\n"
      end)

    "| id | function | mutation | status | killers |\n|---|---|---|---|---|\n" <> rows
  end

  # A pipe would end a table cell early; a newline would end the row.
  defp cell(value),
    do: value |> to_string() |> String.replace("|", "\\|") |> String.replace("\n", " ")

  defp mutants(_h, [], _ctx), do: "None.\n"

  defp mutants(h, outcomes, ctx), do: Enum.map_join(outcomes, "\n", &mutant(h, &1, ctx))

  defp mutant(h, %{mutant: m} = o, ctx) do
    [
      "#{h} #{m.id} #{mfa(m)} #{operator(m)}: #{o.status}",
      "",
      @fence <> "diff",
      String.trim_trailing(m.patch, "\n"),
      @fence,
      "",
      command_line(o, ctx),
      "",
      @fence,
      first_failure(o),
      @fence,
      ""
    ]
    |> Enum.join("\n")
  end

  defp operator(%{operator: op, variant: nil}), do: "#{op}"
  defp operator(%{operator: op, variant: variant}), do: "#{op} [#{variant}]"

  defp command_line(%{selection: {source, tests}} = o, ctx) do
    run = Map.get(o, :test_run)
    total = if run, do: run.total, else: 0
    failed = if run, do: length(run.failures), else: 0
    cmd = Enum.join(ctx.test_command ++ tests, " ")

    "Command: `#{cmd}` (#{total} tests, #{failed} failures; tests selected by #{source}). " <>
      "Failed: #{failed_list(o)}"
  end

  defp failed_list(%{killers: []}), do: "none"
  defp failed_list(%{killers: killers}), do: Enum.map_join(killers, ", ", &KillMap.killer/1)

  defp first_failure(%{status: :killed} = o) do
    case Map.get(o, :test_run) do
      %{failures: [first | _]} -> "#{first.file}:#{first.line} #{first.name}\n#{first.text}"
      _none -> o.killers |> hd() |> KillMap.killer()
    end
  end

  # A per-test timeout (DND-5653) quotes ExUnit's own timeout failure; a run
  # the time bound stopped has none to quote.
  defp first_failure(%{status: :timeout} = o) do
    case Map.get(o, :test_run) do
      %{status: :failed, failures: [first | _]} ->
        "#{first.file}:#{first.line} #{first.name}\n#{first.text}"

      _bound ->
        "(the time bound killed the test run)"
    end
  end

  defp first_failure(%{status: :survived}), do: "(no test failed)"
  defp first_failure(%{reason: reason}) when is_binary(reason), do: reason
  defp first_failure(%{status: status}), do: "(#{status})"

  defp survivors(outcomes) do
    case for(%{status: :survived} = o <- outcomes, do: o) do
      [] ->
        "None.\n"

      survived ->
        Enum.map_join(survived, "", fn %{mutant: m} ->
          "- #{m.id} #{mfa(m)} #{operator(m)}: the selected tests ran and passed. " <>
            "Fix: add a test that fails under this mutant\n"
        end)
    end
  end

  defp timeout_kills(outcomes) do
    case for(%{status: :timeout} = o <- outcomes, do: o) do
      [] ->
        "None.\n"

      timed_out ->
        Enum.map_join(timed_out, "", fn %{mutant: m} = o ->
          "- #{m.id} #{mfa(m)} #{operator(m)}: #{failed_list(o)}. " <>
            "No assertion failed: a hang the mutant caused, or a slow host\n"
        end)
    end
  end

  defp not_measured(items, outcomes) do
    lines =
      for(%{status: s} = o <- outcomes, s in [:invalid, :no_tests, :crashed], do: unmeasured(o)) ++
        for(
          {:skipped, s} <- items,
          do: "- skipped #{mfa(s)} #{operator(s)} `#{s.target}`: #{s.reason}"
        ) ++
        for({:not_run, m} <- items, do: "- #{m.id} #{mfa(m)} #{operator(m)}: not run (cap)") ++
        for({:error, {f, reason}} <- items, do: "- #{mfa(f)}: #{error_text(reason)}")

    case lines do
      [] -> "None.\n"
      lines -> Enum.join(lines, "\n") <> "\n"
    end
  end

  defp unmeasured(%{mutant: m, status: :no_tests} = o),
    do: "- #{m.id} #{mfa(m)} #{operator(m)}: no_tests (no test selected; looked for #{o.reason})"

  defp unmeasured(%{mutant: m, status: :crashed} = o),
    do: "- #{m.id} #{mfa(m)} #{operator(m)}: crashed (#{o.reason})"

  defp unmeasured(%{mutant: m} = o),
    do: "- #{m.id} #{mfa(m)} #{operator(m)}: invalid (#{o.reason})"

  defp error_text(:not_in_source), do: "not in source (no literal def/defp clause: no mutant)"
  defp error_text({:parse_error, line, message}), do: "does not parse at line #{line}: #{message}"
  defp error_text({:unreadable, posix}), do: "could not be read (#{inspect(posix)})"
  defp error_text(other), do: inspect(other)

  defp lacking_lines([], _ctx), do: "None.\n"

  defp lacking_lines(tests, ctx) do
    Enum.map_join(tests, "", fn t ->
      "- #{t.file}:#{t.line} \"#{t.name}\": no generated mutant failed it. " <>
        "It still needs a hand sabotage (#{ctx.records.adr}).\n"
    end)
  end

  defp mfa(%{module: module, function: {name, arity}}), do: "#{inspect(module)}.#{name}/#{arity}"
  defp mfa(%{module: module, name: name, arity: arity}), do: "#{inspect(module)}.#{name}/#{arity}"
end
